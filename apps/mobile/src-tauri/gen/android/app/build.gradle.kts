import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("rust")
}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

android {
    compileSdk = 37
    namespace = "io.github.lampe332.lorelamp"
    defaultConfig {
        // The app reaches Lorelamp on a PC in the home network, where only plain HTTP exists.
        // Which addresses it may open is checked in the Rust part (src/link.rs).
        manifestPlaceholders["usesCleartextTraffic"] = "true"
        applicationId = "io.github.lampe332.lorelamp"
        minSdk = 24
        targetSdk = 37
        versionCode = tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
        versionName = tauriProperties.getProperty("tauri.android.versionName", "1.0")
    }
    // Release signing: the key never lives in this repository. scripts/release-android.ps1 passes
    // its place and password in these variables; without them the release APK stays unsigned.
    val signingStore = providers.environmentVariable("LORELAMP_SIGNING_STORE").orNull
    val signingPassword = providers.environmentVariable("LORELAMP_SIGNING_PASSWORD").orNull
    if (signingStore != null && signingPassword != null) {
        signingConfigs.create("release") {
            storeFile = file(signingStore)
            storeType = "PKCS12"
            storePassword = signingPassword
            keyAlias = providers.environmentVariable("LORELAMP_SIGNING_ALIAS").orNull ?: "lorelamp"
            keyPassword = signingPassword
        }
    }
    buildTypes {
        getByName("debug") {
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            signingConfig = signingConfigs.findByName("release")
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_1_8
    }
}

rust {
    rootDirRel = "../../../"
}

