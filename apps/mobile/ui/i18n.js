/** "de-AT" → "de"; a language without words of its own gets English. */
const LANG = (() => {
  const code = (navigator.language || '').slice(0, 2).toLowerCase();
  return Object.prototype.hasOwnProperty.call(WORDS, code) ? code : 'en';
})();

/** The text for `key`, with `{name}` places filled from `values`. */
function t(key, values) {
  const text = WORDS[LANG][key] || WORDS.en[key] || key;
  return values ? text.replace(/\{(\w+)\}/g, (all, name) => (name in values ? String(values[name]) : all)) : text;
}

/** Fills every element marked `data-i18n` (its text) or `data-i18n-label` (its aria-label). */
function translatePage() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
}

translatePage();
